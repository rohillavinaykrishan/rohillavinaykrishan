#!/usr/bin/env python3
"""Build kit.js = kit_src.js + cues.json inlined (HyperFrames forbids fetch at render time).
Re-run whenever the Director regenerates cues.json:  python3 make_kit.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
CUES = os.path.normpath(os.path.join(HERE, "../../../director/v001/cues.json"))
c = json.load(open(CUES))
keep = {k: c[k] for k in ["project", "title", "fps", "frames", "size", "beats_f", "events",
                          "layout_4k", "shots", "tiles", "palette", "fonts"] if k in c}
src = open(os.path.join(HERE, "kit_src.js")).read()
assert "/*__CUES__*/ null" in src
out = src.replace("/*__CUES__*/ null", "/* inlined from director/v001/cues.json by make_kit.py */ " + json.dumps(keep, separators=(",", ":")))
out = out.replace("-- SOURCE.", "-- GENERATED by make_kit.py from kit_src.js + cues.json.")
open(os.path.join(HERE, "kit.js"), "w").write(out)
print("kit.js", len(out), "bytes; cues mtime", os.path.getmtime(CUES))
